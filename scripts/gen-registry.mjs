// Scans src/registry/items/<slug>/ and writes the two generated index files.
// Runs before dev/build; safe to run concurrently (atomic rename).
import { existsSync, readdirSync, renameSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "../src/registry");
const itemsDir = path.join(root, "items");
const outDir = path.join(root, "generated");
mkdirSync(outDir, { recursive: true });

const slugs = readdirSync(itemsDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && /^[a-z0-9-]+$/.test(d.name))
  .map((d) => d.name)
  .filter((s) => ["meta.ts", "demo.tsx", `${s}.tsx`].every((f) => existsSync(path.join(itemsDir, s, f))))
  .sort();

const id = (s) => "m_" + s.replace(/-/g, "_");
const header = "// GENERATED by scripts/gen-registry.mjs. Do not edit.\n";

const metas =
  header +
  `import type { RegistryEntry } from "../types";\n` +
  slugs.map((s) => `import ${id(s)} from "../items/${s}/meta";`).join("\n") +
  `\n\nexport const registry: RegistryEntry[] = [\n` +
  slugs.map((s) => `  { slug: "${s}", ...${id(s)} },`).join("\n") +
  `\n];\n`;

const demos =
  header +
  `"use client";\n\nimport { lazy, type ComponentType } from "react";\n\n` +
  `export const demos: Record<string, ComponentType<Record<string, unknown>>> = {\n` +
  slugs.map((s) => `  "${s}": lazy(() => import("../items/${s}/demo")),`).join("\n") +
  `\n};\n`;

const write = (file, content) => {
  const tmp = `${file}.${process.pid}.tmp`;
  writeFileSync(tmp, content);
  renameSync(tmp, file);
};
write(path.join(outDir, "metas.ts"), metas);
write(path.join(outDir, "demos.tsx"), demos);
console.log(`registry: ${slugs.length} components`);
