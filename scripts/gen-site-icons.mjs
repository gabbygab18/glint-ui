// Pre-renders the icons the site uses (the named(...) list in src/components/site-icons.tsx)
// from the icons-website project next to this repo, so the site ships ~31 icons instead of all 351.
// usage: node scripts/gen-site-icons.mjs   (needs ../icons-website and Node 22+ for .ts imports)
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { BY_NAME, renderInner } from "../../icons-website/src/icons/render.ts";

const root = path.resolve(import.meta.dirname, "..");
const names = [...readFileSync(path.join(root, "src/components/site-icons.tsx"), "utf8").matchAll(/named\("([^"]+)"\)/g)].map((m) => m[1]);
const missing = names.filter((n) => !BY_NAME.has(n));
if (missing.length) throw new Error(`Unknown icons: ${missing.join(", ")}`);

// Filled style, stroke 2. "__ID__" is swapped for a unique mask id per rendered icon.
const out = Object.fromEntries(names.sort().map((n) => [n, renderInner(BY_NAME.get(n), { variant: "solid", stroke: 2, id: "__ID__" })]));
writeFileSync(
  path.join(root, "src/icons/site.ts"),
  `// GENERATED by scripts/gen-site-icons.mjs from the icons-website project. Do not edit.\nexport const SITE_ICONS: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`site icons: ${names.length}`);
